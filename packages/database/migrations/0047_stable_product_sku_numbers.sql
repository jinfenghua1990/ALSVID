CREATE SEQUENCE product.product_id_seq
  AS bigint MINVALUE 100001 MAXVALUE 999999 START WITH 100001 NO CYCLE;

ALTER TABLE product.models
  ADD COLUMN product_id bigint,
  ADD COLUMN next_sku_sequence smallint NOT NULL DEFAULT 1;

DO $$
BEGIN
  IF (SELECT count(*) FROM product.models) > 899999 THEN
    RAISE EXCEPTION 'Six-digit Product ID capacity exceeded';
  END IF;
  IF EXISTS (
    SELECT 1
    FROM product.skus s
    JOIN product.variants v ON v.id=s.variant_id
    GROUP BY v.model_id HAVING count(*) > 999
  ) THEN
    RAISE EXCEPTION 'A product already has more than 999 SKUs; manual ID mapping is required';
  END IF;
END;
$$;

WITH numbered AS (
  SELECT id, 100000 + row_number() OVER (ORDER BY created_at,id) AS product_id
  FROM product.models
)
UPDATE product.models m SET product_id=n.product_id
FROM numbered n WHERE n.id=m.id;

SELECT setval('product.product_id_seq',
  COALESCE((SELECT max(product_id) FROM product.models),100001),
  EXISTS(SELECT 1 FROM product.models));

ALTER TABLE product.models
  ALTER COLUMN product_id SET NOT NULL,
  ALTER COLUMN product_id SET DEFAULT nextval('product.product_id_seq'),
  ADD CONSTRAINT product_models_product_id_unique UNIQUE(product_id),
  ADD CONSTRAINT product_models_product_id_range CHECK(product_id BETWEEN 100001 AND 999999),
  ADD CONSTRAINT product_models_next_sku_sequence_range CHECK(next_sku_sequence BETWEEN 1 AND 1000);

ALTER SEQUENCE product.product_id_seq OWNED BY product.models.product_id;

ALTER TABLE product.skus
  ADD COLUMN product_id bigint,
  ADD COLUMN sku_number bigint,
  ADD COLUMN sku_sequence smallint;

WITH numbered AS (
  SELECT s.id,m.product_id,
    row_number() OVER(PARTITION BY m.id ORDER BY s.created_at,s.id)::smallint AS sku_sequence
  FROM product.skus s
  JOIN product.variants v ON v.id=s.variant_id
  JOIN product.models m ON m.id=v.model_id
)
UPDATE product.skus s
SET product_id=n.product_id,
    sku_sequence=n.sku_sequence,
    sku_number=n.product_id*1000+n.sku_sequence
FROM numbered n WHERE n.id=s.id;

UPDATE product.models m SET next_sku_sequence=COALESCE((
  SELECT max(s.sku_sequence)+1 FROM product.skus s WHERE s.product_id=m.product_id
),1);

ALTER TABLE product.skus
  ALTER COLUMN product_id SET NOT NULL,
  ALTER COLUMN sku_number SET NOT NULL,
  ALTER COLUMN sku_sequence SET NOT NULL,
  ADD CONSTRAINT product_skus_product_id_fk FOREIGN KEY(product_id)
    REFERENCES product.models(product_id) ON DELETE RESTRICT,
  ADD CONSTRAINT product_skus_sku_number_unique UNIQUE(sku_number),
  ADD CONSTRAINT product_skus_sku_sequence_unique UNIQUE(product_id,sku_sequence),
  ADD CONSTRAINT product_skus_sku_number_shape CHECK(
    sku_number=product_id*1000+sku_sequence AND sku_sequence BETWEEN 1 AND 999
  );

CREATE OR REPLACE FUNCTION product.guard_stable_product_id()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP='DELETE' THEN
    RAISE EXCEPTION 'Products are retired, never physically deleted';
  END IF;
  IF TG_OP='UPDATE' AND NEW.product_id IS DISTINCT FROM OLD.product_id THEN
    RAISE EXCEPTION 'Product ID is immutable';
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER product_models_stable_product_id_guard
BEFORE UPDATE OR DELETE ON product.models
FOR EACH ROW EXECUTE FUNCTION product.guard_stable_product_id();

CREATE OR REPLACE FUNCTION product.assign_stable_sku_number()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
  target_model uuid;
  allocated_product_id bigint;
  allocated_sequence smallint;
BEGIN
  IF TG_OP='DELETE' THEN
    RAISE EXCEPTION 'SKUs are retired, never physically deleted';
  END IF;

  IF TG_OP='UPDATE' THEN
    IF NEW.product_id IS DISTINCT FROM OLD.product_id
      OR NEW.sku_number IS DISTINCT FROM OLD.sku_number
      OR NEW.sku_sequence IS DISTINCT FROM OLD.sku_sequence
      OR NEW.variant_id IS DISTINCT FROM OLD.variant_id THEN
      RAISE EXCEPTION 'SKU identity and owning product are immutable';
    END IF;
    RETURN NEW;
  END IF;

  IF NEW.sku_number IS NOT NULL OR NEW.sku_sequence IS NOT NULL OR NEW.product_id IS NOT NULL THEN
    RAISE EXCEPTION 'SKU identity is generated by the database';
  END IF;

  SELECT v.model_id INTO target_model FROM product.variants v WHERE v.id=NEW.variant_id;
  IF target_model IS NULL THEN
    RAISE EXCEPTION 'Variant not found' USING ERRCODE='23503';
  END IF;

  UPDATE product.models m
  SET next_sku_sequence=m.next_sku_sequence+1
  WHERE m.id=target_model AND m.next_sku_sequence<=999
  RETURNING m.product_id,m.next_sku_sequence-1
  INTO allocated_product_id,allocated_sequence;

  IF allocated_product_id IS NULL THEN
    RAISE EXCEPTION 'Product has exhausted its 999 SKU IDs';
  END IF;

  NEW.product_id:=allocated_product_id;
  NEW.sku_sequence:=allocated_sequence;
  NEW.sku_number:=allocated_product_id*1000+allocated_sequence;
  RETURN NEW;
END;
$$;

CREATE TRIGGER product_skus_stable_number_guard
BEFORE INSERT OR UPDATE OR DELETE ON product.skus
FOR EACH ROW EXECUTE FUNCTION product.assign_stable_sku_number();

CREATE INDEX product_skus_product_id_idx ON product.skus(product_id,sku_sequence);

-- Every model must have at least one SKU, including older records created
-- before the default-SKU rule existed.
INSERT INTO product.variants(model_id,code,name,description,attributes,status)
SELECT m.id,'DEFAULT','Default','', '{}'::jsonb,m.status
FROM product.models m
WHERE NOT EXISTS(SELECT 1 FROM product.variants v WHERE v.model_id=m.id);

INSERT INTO product.skus(variant_id,sku,name,status)
SELECT v.id,'ALS-DEF-'||m.product_id::text,m.name||' - Default',m.status
FROM product.models m
JOIN LATERAL (
  SELECT v.id FROM product.variants v
  WHERE v.model_id=m.id ORDER BY v.created_at,v.id LIMIT 1
) v ON true
WHERE NOT EXISTS(
  SELECT 1 FROM product.skus s
  JOIN product.variants existing_variant ON existing_variant.id=s.variant_id
  WHERE existing_variant.model_id=m.id
);

ALTER TABLE commerce.storefront_order_lines
  ADD COLUMN product_id_snapshot bigint,
  ADD COLUMN sku_number_snapshot bigint;

UPDATE commerce.storefront_order_lines l
SET product_id_snapshot=s.product_id,sku_number_snapshot=s.sku_number
FROM product.skus s WHERE s.id=l.sku_id;

ALTER TABLE commerce.storefront_order_lines
  ALTER COLUMN product_id_snapshot SET NOT NULL,
  ALTER COLUMN sku_number_snapshot SET NOT NULL,
  ADD CONSTRAINT storefront_order_line_product_snapshot_fk
    FOREIGN KEY(product_id_snapshot) REFERENCES product.models(product_id) ON DELETE RESTRICT,
  ADD CONSTRAINT storefront_order_line_sku_snapshot_fk
    FOREIGN KEY(sku_number_snapshot) REFERENCES product.skus(sku_number) ON DELETE RESTRICT;

CREATE OR REPLACE FUNCTION commerce.capture_storefront_product_ids()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  SELECT s.product_id,s.sku_number
  INTO NEW.product_id_snapshot,NEW.sku_number_snapshot
  FROM product.skus s WHERE s.id=NEW.sku_id;
  IF NEW.product_id_snapshot IS NULL OR NEW.sku_number_snapshot IS NULL THEN
    RAISE EXCEPTION 'Storefront order SKU not found' USING ERRCODE='23503';
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER storefront_order_line_capture_product_ids
BEFORE INSERT ON commerce.storefront_order_lines
FOR EACH ROW EXECUTE FUNCTION commerce.capture_storefront_product_ids();

ALTER TABLE commerce.external_order_lines
  ADD COLUMN product_id bigint,
  ADD COLUMN sku_number bigint;

UPDATE commerce.external_order_lines l
SET product_id=s.product_id,sku_number=s.sku_number
FROM product.skus s WHERE s.id=l.sku_id;

CREATE OR REPLACE FUNCTION commerce.sync_external_order_line_product_ids()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.sku_id IS NULL THEN
    NEW.product_id:=NULL;
    NEW.sku_number:=NULL;
  ELSE
    SELECT s.product_id,s.sku_number INTO NEW.product_id,NEW.sku_number
    FROM product.skus s WHERE s.id=NEW.sku_id;
    IF NEW.product_id IS NULL OR NEW.sku_number IS NULL THEN
      RAISE EXCEPTION 'Mapped external order SKU not found' USING ERRCODE='23503';
    END IF;
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER external_order_line_sync_product_ids
BEFORE INSERT OR UPDATE OF sku_id ON commerce.external_order_lines
FOR EACH ROW EXECUTE FUNCTION commerce.sync_external_order_line_product_ids();
