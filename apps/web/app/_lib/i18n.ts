const dictionaries: Record<Locale, Record<TranslationKey, string>> = { en, de };

export function isLocale(value: string | undefined): value is Locale {
  return ENABLED_LOCALES.some((locale) => locale === value);
}

export function t(locale: Locale, key: TranslationKey): string {
  const value = dictionaries[locale][key];
  if (value) return value;
  if (process.env.NODE_ENV !== 'production') console.warn(`Missing ALSVID translation: ${locale}.${key}`);
  return dictionaries.en[key] ?? key;
}
