import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
const require = createRequire(path.join(process.env.FC1_PLAYWRIGHT_ROOT, 'package.json'));
const { chromium } = require('playwright');
const output = process.env.FC1_REVIEW_OUTPUT || '.tmp/fc1-v4-review';
const base = 'http://127.0.0.1:3000';
await mkdir(output, { recursive: true });
const browser = await chromium.launch();
const report = { sha: process.env.FC1_REVIEW_SHA, checks: [] };
try {
  for (const locale of ['zh', 'de', 'en']) {
    const copy = JSON.parse(await readFile('apps/web/app/_lib/i18n/shop-preview/' + locale + '.json', 'utf8'));
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
    const page = await context.newPage();
    const errors = [];
    const mutations = [];
    page.on('pageerror', error => errors.push(error.message));
    page.on('request', request => { if (['POST', 'PUT', 'PATCH', 'DELETE'].includes(request.method())) mutations.push(request.url()); });
    await page.goto(base + '/' + locale + '/shop-preview/reference');
    const preview = page.locator('[data-shop-preview]');
    await preview.waitFor();
    assert.equal(await page.locator('[data-public-site-header]').count(), 1);
    assert.match(await page.locator('meta[name="robots"]').getAttribute('content'), /noindex/);
    assert.equal(await preview.locator('[data-preview-model]').count(), 2);
    const original = await page.evaluate(() => JSON.stringify({ ...localStorage }));
    await preview.getByRole('button', { name: 'Pro', exact: true }).click();
    await preview.locator('[data-preview-model="fc1"]').getByRole('button', { name: copy['shopPreview.add'], exact: true }).click();
    const bagLabel = copy['shopPreview.bag'].replace('{count}', '1');
    await preview.getByRole('button', { name: bagLabel, exact: true }).click();
    const bag = preview.locator('#independent-preview-bag');
    assert.equal(await bag.isVisible(), true);
    assert.match(await bag.innerText(), /Pro/);
    await bag.getByRole('spinbutton').fill('2');
    assert.equal(await bag.getByRole('button', { name: copy['shopPreview.noCheckout'], exact: true }).isDisabled(), true);
    await page.reload();
    await preview.waitFor();
    await preview.getByRole('button', { name: copy['shopPreview.bag'].replace('{count}', '2'), exact: true }).click();
    assert.equal(await bag.getByRole('spinbutton').inputValue(), '2');
    assert.equal(await page.evaluate(() => JSON.stringify({ ...localStorage })), original);
    await page.screenshot({ path: path.join(output, 'shop-preview-' + locale + '-desktop.png'), fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    await page.screenshot({ path: path.join(output, 'shop-preview-' + locale + '-mobile.png'), fullPage: true });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), locale + ' fits mobile');
    await preview.getByRole('searchbox').fill('does-not-exist');
    assert.equal(await preview.locator('[data-preview-model]').count(), 0);
    await preview.getByRole('button', { name: copy['shopPreview.clear'], exact: true }).click();
    assert.equal(await preview.locator('[data-preview-model]').count(), 2);
    assert.deepEqual(mutations, [], 'preview never writes business APIs');
    assert.deepEqual(errors, [], locale + ' has no runtime errors');
    await page.goto(base + '/' + locale + '/bikes');
    const link = page.locator('[data-shop-preview-entry] a');
    assert.equal(await link.getAttribute('href'), '/' + locale + '/shop-preview');
    report.checks.push(locale + ': shared header, noindex, bag selection/quantity/reload, storage isolation, empty state, desktop/mobile, entry link');
    await context.close();
  }
  await writeFile(path.join(output, 'shop-preview-report.json'), JSON.stringify(report, null, 2));
} finally { await browser.close(); }
